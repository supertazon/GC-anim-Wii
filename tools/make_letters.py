#!/usr/bin/env python3
"""Generate source/letters_data.c from letters_design.py (needs shapely >= 2.1).

usage: python3 tools/make_letters.py [source/letters_data.c]

Each glyph is extruded to the thickness of the IPL letters and written as two triangle lists
(caps and side walls), s16 positions with 8 fractional bits, wound for GX_CULL_BACK like the IPL's.
"""
import os, sys
import shapely
from shapely.geometry import Polygon
from shapely.geometry.polygon import orient
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from letters_design import G

Z = 3.254          # half thickness of the IPL letters
FRAC = 256.0

def polys(g):
    return list(g.geoms) if hasattr(g, 'geoms') else [g]

def q(v):
    return int(round(v * FRAC))

def mesh(c):
    g = G(c).buffer(0)
    caps, walls = [], []
    for p in polys(g):
        if p.is_empty or p.geom_type != 'Polygon':
            continue
        p = orient(p.simplify(0.01), 1.0)
        tri = shapely.constrained_delaunay_triangles(p)
        for t in tri.geoms:
            (a, b, cc) = list(t.exterior.coords)[:3]
            # make it counter-clockwise in xy
            area = (b[0] - a[0]) * (cc[1] - a[1]) - (b[1] - a[1]) * (cc[0] - a[0])
            if area < 0:
                b, cc = cc, b
            if abs(area) < 1e-6:
                continue
            caps.append([(a[0], a[1], Z), (cc[0], cc[1], Z), (b[0], b[1], Z)])     # front: clockwise from +z
            caps.append([(a[0], a[1], -Z), (b[0], b[1], -Z), (cc[0], cc[1], -Z)])  # back: counter-clockwise
        for ring in [p.exterior] + list(p.interiors):
            pts = list(ring.coords)
            for (x0, y0), (x1, y1) in zip(pts[:-1], pts[1:]):
                A, B, C, D = (x0, y0, Z), (x1, y1, Z), (x1, y1, -Z), (x0, y0, -Z)
                walls.append([A, B, C])
                walls.append([A, C, D])
    return caps, walls

def emit(f, name, tris):
    f.write('static const s16 %s[] ATTRIBUTE_ALIGN(32) = {\n' % name)
    for t in tris:
        f.write('\t' + ', '.join('%d, %d, %d' % (q(x), q(y), q(z)) for x, y, z in t) + ',\n')
    f.write('};\n')

def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', 'source', 'letters_data.c')
    letters = [chr(ord('A') + i) for i in range(26)]
    with open(out, 'w') as f:
        f.write('/* generated by tools/make_letters.py from tools/letters_design.py - do not edit */\n')
        f.write('#include "letters.h"\n\n')
        info = []
        for c in letters:
            caps, walls = mesh(c)
            emit(f, 'cap_%s' % c, caps)
            emit(f, 'wall_%s' % c, walls)
            info.append((c, len(caps), len(walls)))
        f.write('\nconst GlyphMesh glyph_mesh[26] = {\n')
        for c, nc, nw in info:
            f.write('\t{%d, %d, cap_%s, wall_%s},\n' % (nc, nw, c, c))
        f.write('};\n')
    print('wrote', out, sum(i[1] + i[2] for i in info), 'triangles')

if __name__ == "__main__":
    main()
